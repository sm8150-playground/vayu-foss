static unsigned int cached_soc_id;
static unsigned int cached_node_id;

static int soc_id_recognised(unsigned int id)
{
    if (id > 0x1b6u) {
        if (id - 0x1b7u > 0x4cu)
            return 0;
        switch (id - 0x1b7u) {
        case 0:
        case 11:
        case 36:
        case 58:
        case 59:
        case 60:
        case 62:
        case 63:
        case 76:
            return 1;
        default:
            return 0;
        }
    }

    if (id >= SOC_MIN_DIRECT && id <= SOC_MAX_DIRECT)
        return (int)((SOC_MASK >> (id - SOC_MIN_DIRECT)) & 1u);

    return id == SOC_DIRECT_ALT_A || id == SOC_DIRECT_ALT_B;
}

static unsigned int soc_id_from_node(void)
{
    FILE *fp;

    if (cached_node_id != 0)
        return cached_node_id;

    fp = fopen(SOC_NODE, "r");
    if (fp != NULL) {
        if (fscanf(fp, "%d", &cached_node_id) == 0)
            cached_node_id = 0;
        fclose(fp);
    }

    return cached_node_id;
}

void get_soc_info(int *out)
{
    unsigned int id = 0;

    if (cached_soc_id != 0) {
        *out = (int)soc_table[cached_soc_id];
        return;
    }

    {
        char value[92];

        if (property_get(SOC_PROPERTY, value, "0") != 0) {
            char *end;
            long parsed;

            errno = 0;
            parsed = strtol(value, &end, 10);
            if (errno != ERANGE && parsed != 0 && end != value)
                id = (unsigned int)parsed;
        }
    }

    if (id == 0 || !soc_id_recognised(id)) {
        id = soc_id_from_node();
        if (!soc_id_recognised(id)) {
            id = 0;
            cached_node_id = 0;
        }
    }

    cached_soc_id = id;
    *out = (int)soc_table[id];
}
